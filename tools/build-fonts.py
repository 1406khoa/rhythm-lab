#!/usr/bin/env python3
"""Build fonts/*.woff2: one file per weight, holding exactly the characters the Vietnamese UI can show.

Why: the stock Google Fonts split (latin / latin-ext / vietnamese) costs 3 files per weight, and every
Vietnamese word needs all three. One subset per weight = 4 requests instead of up to 15, and 64 KB instead of 216 KB.

Needs: pip install fonttools brotli
Source fonts (SIL OFL 1.1): Barlow-Regular.ttf, Barlow-Medium.ttf, Barlow-SemiBold.ttf, BarlowCondensed-SemiBold.ttf
from https://fonts.google.com/specimen/Barlow and .../Barlow+Condensed ("Get font" -> download).

Usage: python3 tools/build-fonts.py --src DIR_WITH_THE_TTF_FILES
Run it again whenever tools/build.js reports a character that is not in fonts/charset.txt.
"""
import glob, os, sys
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "fonts")
FACES = {"Barlow-Regular": "barlow-400", "Barlow-Medium": "barlow-500", "Barlow-SemiBold": "barlow-600",
         "BarlowCondensed-SemiBold": "barlow-condensed-600"}
TEXT_FILES = ["index.html", "js/*.js", "js/core/*.js", "js/tabs/*.js", "css/app.css", "manifest.webmanifest"]  # same list as tools/build.js
SKIP = ("selftest", "vocal-samples")
VIET = "àáảãạăằắẳẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđ"
EXTRA = " –—‘’“”…·×"  # punctuation worth having even before the UI uses it


def app_chars():
    used = set()
    for pat in TEXT_FILES:
        for f in glob.glob(os.path.join(ROOT, pat)):
            if not any(s in f for s in SKIP):
                used |= set(open(f, encoding="utf-8").read())
    return {c for c in used if ord(c) > 0x7e}


def main():
    src = sys.argv[sys.argv.index("--src") + 1] if "--src" in sys.argv else sys.exit(__doc__)
    want = set(map(chr, range(0x20, 0x7f))) | set(VIET) | set(VIET.upper()) | set(EXTRA) | app_chars()
    covered = None
    for name, out in FACES.items():
        ttf = os.path.join(src, name + ".ttf")
        cmap = TTFont(ttf).getBestCmap()
        have = sorted(c for c in want if ord(c) in cmap)
        covered = set(have) if covered is None else covered & set(have)
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["kern", "liga", "mark", "mkmk", "ccmp", "locl", "tnum"]  # tnum: the app sets tabular-nums
        opts.name_IDs = [1, 2]
        opts.notdef_outline = True
        font = subset.load_font(ttf, opts)
        s = subset.Subsetter(opts)
        s.populate(unicodes=[ord(c) for c in have])
        s.subset(font)
        dst = os.path.join(OUT, out + ".woff2")
        subset.save_font(font, dst, opts)
        print(f"{out + '.woff2':28s}{os.path.getsize(dst) / 1024:6.1f} KB  {len(have)} characters")
    missing = sorted(want - covered)  # Barlow has no glyph: the browser falls back to a system font (symbols, emoji)
    with open(os.path.join(OUT, "charset.txt"), "w", encoding="utf-8") as f:
        f.write("# generated by tools/build-fonts.py. Line 2: characters in the fonts. Line 3: used by the app, not in Barlow (system font).\n")
        f.write("".join(sorted(covered)) + "\n" + "".join(missing) + "\n")
    print("not in Barlow (shown in a system font):", " ".join(missing))


if __name__ == "__main__":
    main()
