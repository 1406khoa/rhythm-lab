#!/usr/bin/env python3
"""Build js/vocal-samples.js from assets/voice-src/* (one speaker: assets/voice-src/english_audio_pack, 1-20 + a-z).

Per sample: mono, trim leading silence, find the perceptual onset (vowel rise),
match loudness, fade tail, encode 16-bit 22.05 kHz FLAC (lossless: decodes to the very same
samples as the WAV it replaces, at ~60% of the size; lossy codecs would shift the onsets by a
browser-dependent encoder delay), embed as base64 so file:// needs no fetch.

Usage: python3 tools/build-samples.py [--src DIR]   (DIR holds 1.* ... 12.*, any audio format)
"""
import base64, io, json, os, subprocess, sys, tempfile, wave
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "voice-src" / "english_audio_pack"
OUT = ROOT / "js" / "vocal-samples.js"
SR = 22050
WORDS = {str(i): str(i) for i in range(1, 13)}
START_DB = -36       # leading trim threshold vs envelope peak (samples carry a -45 dB noise floor)
END_DB = -30         # trailing trim threshold (tails decay into noise)
START_DB_OVERRIDE = {}
MAX_LEN_OVERRIDE = {}
PRE_ROLL = 0.012     # keep a little lead-in so the attack is not clipped
ONSET_FRAC = 0.25    # perceptual onset = smoothed envelope first reaches 25% of its peak
MAX_LEN = 0.60
TARGET_RMS = 0.12


def load(path):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(SR),
                          "-f", "f32le", "-"], capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.float32).copy()


def envelope(x, win=0.008):
    n = max(1, int(SR * win))
    return np.sqrt(np.convolve(x * x, np.ones(n) / n, mode="same"))


def f0_median(x):
    """Median pitch of voiced frames (autocorrelation, 70-300 Hz)."""
    fl, hop, vals = int(SR * 0.04), int(SR * 0.01), []
    for i in range(0, len(x) - fl, hop):
        f = x[i:i + fl] - x[i:i + fl].mean()
        if np.sqrt((f * f).mean()) < 0.02:
            continue
        ac = np.correlate(f, f, "full")[fl - 1:]
        lo, hi = int(SR / 300), int(SR / 70)
        k = lo + int(np.argmax(ac[lo:hi]))
        if ac[k] > 0.5 * ac[0]:
            vals.append(SR / k)
    return float(np.median(vals)) if vals else 0.0


def process(path, start_db=START_DB, max_len=MAX_LEN):
    x = load(path)
    x = x / (np.abs(x).max() + 1e-9)
    env = envelope(x)
    peak = env.max()
    a = int(np.argmax(env > peak * 10 ** (start_db / 20)))
    b = int(np.where(env > peak * 10 ** (END_DB / 20))[0][-1])
    a = max(0, a - int(SR * PRE_ROLL))
    x = x[a:min(b + int(SR * 0.02), a + int(SR * max_len))]
    env = envelope(x, 0.010)
    onset = int(np.argmax(env >= ONSET_FRAC * env.max()))
    fade = int(SR * 0.02)
    x[-fade:] *= np.linspace(1, 0, fade)
    rms = np.sqrt((x * x).mean())
    x = np.clip(x * (TARGET_RMS / rms), -0.98, 0.98)
    return x, onset / SR, f0_median(x)


def flac_b64(x):
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((x * 32767).astype("<i2").tobytes())
    with tempfile.TemporaryDirectory() as d:  # a real file, not a pipe: ffmpeg must seek back to finish the FLAC header
        out = os.path.join(d, "s.flac")
        subprocess.run(["ffmpeg", "-v", "error", "-f", "wav", "-i", "-", "-c:a", "flac", "-compression_level", "12", "-metadata_header_padding", "0", out],
                       input=buf.getvalue(), check=True)
        return base64.b64encode(open(out, "rb").read()).decode()


def main():
    out, report = {}, []
    src = Path(sys.argv[sys.argv.index("--src") + 1]) if "--src" in sys.argv else SRC
    for stem, key in WORDS.items():
        found = sorted(src.glob(f"{stem}.*"))
        if not found:
            sys.exit(f"missing {stem}.* in {src}")
        x, onset, f0 = process(found[0], START_DB_OVERRIDE.get(stem, START_DB), MAX_LEN_OVERRIDE.get(stem, MAX_LEN))
        out[key] = {"onset": round(onset, 4), "dur": round(len(x) / SR, 4), "flac": flac_b64(x)}
        report.append((key, onset * 1000, len(x) / SR * 1000, f0))
    OUT.write_text("/* generated by tools/build-samples.py - do not edit */\n"
                   "window.RT = window.RT || {};\nRT.VOCAL = " + json.dumps(out) + ";\n")
    print(f"{'word':6}{'onset ms':>10}{'dur ms':>9}{'f0 Hz':>8}")
    for k, o, d, f in report:
        print(f"{k:6}{o:10.1f}{d:9.1f}{f:8.0f}")
    f0s = [f for *_, f in report if f]
    print(f"f0 median {np.median(f0s):.0f} Hz, range {min(f0s):.0f}-{max(f0s):.0f}; wrote {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
